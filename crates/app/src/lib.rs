//! AdsConsole desktop app. `core` holds the logic with no Tauri; `shell` wires it to
//! the window, the commands and the menu bar.

pub mod core;
mod shell;

/// Path of the generated UI types, relative to this crate.
const BINDINGS: &str = "../../ui/src/bindings.ts";

pub fn run() {
    let builder = shell::commands::builder();
    if std::env::args().any(|a| a == "--export-bindings") {
        export(&builder);
        return;
    }
    #[cfg(debug_assertions)]
    export(&builder);
    shell::run(builder, std::env::args().any(|a| a == "--demo"));
}

fn export(builder: &tauri_specta::Builder<::tauri::Wry>) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS);
    let ts = specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta. Do not edit.\n");
    if let Err(e) = builder.export(ts, &path) {
        eprintln!("failed to generate {}: {e}", path.display());
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    /// Every type exposed to the UI must be exportable to TypeScript.
    #[test]
    fn bindings_export() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("bindings.ts");
        super::shell::commands::builder()
            .export(specta_typescript::Typescript::default(), &path)
            .unwrap();
        let ts = std::fs::read_to_string(path).unwrap();
        assert!(ts.contains("listPending"));
        assert!(ts.contains("app-event-msg"));
    }
}
