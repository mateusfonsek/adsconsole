fn locale(name: &str) -> Option<&'static [&'static str; 12]> {
    TABLE.iter().find(|(l, _)| *l == name).map(|(_, t)| t)
}

/// Canonical form of `typed`: any value in the table (any locale, plus English),
/// ignoring case and surrounding spaces. An exact match wins.
pub(super) fn canonical(typed: &str) -> Option<&'static str> {
    let typed = typed.trim();
    let all = || {
        ENGLISH
            .iter()
            .chain(TABLE.iter().flat_map(|(_, texts)| texts.iter()))
            .copied()
            .filter(|t| !t.is_empty())
    };
    all().find(|t| *t == typed).or_else(|| {
        let lower = typed.to_lowercase();
        all().find(|t| t.to_lowercase() == lower)
    })
}

/// Options in pt-BR and in English, for the error message.
pub(super) fn options() -> String {
    let pt: Vec<&str> = locale("pt-BR")
        .map(|t| t.iter().copied().filter(|s| !s.is_empty()).collect())
        .unwrap_or_default();
    format!(
        "Portuguese (pt-BR): {}. English: {}.",
        pt.join(", "),
        ENGLISH.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_matches_the_published_shape() {
        assert_eq!(TABLE.len(), 45);
        assert_eq!(locale("en"), Some(&ENGLISH));
    }

    #[test]
    fn canonical_is_case_and_space_insensitive() {
        assert_eq!(canonical(" comprar AGORA "), Some("Comprar agora"));
        assert_eq!(canonical("Apply now"), Some("Apply now"));
        assert_eq!(canonical("apply now"), Some("Apply Now"));
        assert_eq!(canonical("Ver mais"), Some("Ver mais"));
        assert_eq!(canonical("comprar já"), Some("Comprar já")); // pt-PT
        assert_eq!(canonical("Compre já"), None);
        assert_eq!(canonical("Compre"), None);
        assert_eq!(canonical(""), None);
    }

    #[test]
    fn options_list_pt_br_and_english() {
        let o = options();
        assert!(
            o.contains("Comprar agora") && o.contains("Saber mais"),
            "{o}"
        );
        assert!(o.contains("Shop Now") && o.contains("Learn More"), "{o}");
    }
}
